import { useEffect, useMemo, useRef, useState } from "react";
import { HeartHandshake, Clock, Download, Award } from "lucide-react";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Progress } from "@/components/ui/progress";

/** A single pro bono mentor / advisor log entry. */
interface MentorLog {
  advisor: string;
  focus: string;
  minutes: number;
}

/** A corporate CSR campaign the tracked hours contribute toward. */
interface CsrCampaign {
  id: string;
  name: string;
  /** Target pro bono hours for the campaign. */
  targetHours: number;
}

const MENTOR_LOGS: MentorLog[] = [
  { advisor: "Priya N.", focus: "SME network isolation review", minutes: 95 },
  { advisor: "Marcus O.", focus: "Serverless migration pairing", minutes: 140 },
  { advisor: "Dana R.", focus: "Privacy compliance walkthrough", minutes: 60 },
];

const CSR_CAMPAIGNS: CsrCampaign[] = [
  { id: "hp-40-days", name: "HP 40 Days of Doing Good Campaign", targetHours: 40 },
  { id: "aws-impact", name: "AWS Impact Track", targetHours: 25 },
];

/** Format a minute count as a short "Xh Ym" string. */
function formatHoursMinutes(totalMinutes: number): string {
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  if (hours === 0) return `${minutes}m`;
  if (minutes === 0) return `${hours}h`;
  return `${hours}h ${minutes}m`;
}

/**
 * Corporate CSR Volunteer Hour Tracker.
 *
 * A dashboard widget that tracks pro bono mentor/advisor logs and automatically
 * accumulates live workspace session time, attributing both toward corporate
 * CSR campaigns. The export button produces a data-verified certificate file
 * suitable for corporate HR documentation.
 *
 * Frontend-only prototype: session time is measured locally from when the
 * widget mounts, and the certificate is generated and downloaded client-side.
 */
export function ResidencyMatch() {
  const [sessionSeconds, setSessionSeconds] = useState(0);
  const mountedAt = useRef(Date.now());

  // Internal state loop: tick live workspace session time every second.
  useEffect(() => {
    const timer = window.setInterval(() => {
      setSessionSeconds(Math.floor((Date.now() - mountedAt.current) / 1000));
    }, 1000);
    return () => window.clearInterval(timer);
  }, []);

  const loggedMinutes = useMemo(
    () => MENTOR_LOGS.reduce((sum, log) => sum + log.minutes, 0),
    [],
  );

  // Live session time contributes toward the tracked CSR total.
  const sessionMinutes = sessionSeconds / 60;
  const totalMinutes = loggedMinutes + sessionMinutes;
  const totalHours = totalMinutes / 60;

  const handleExport = () => {
    const generatedAt = new Date();
    const verificationId = `CSR-${mountedAt.current.toString(36).toUpperCase()}-${Math.round(
      totalMinutes,
    )}`;
    const lines = [
      "ProReady — Verified CSR Impact Hour Certificate",
      "===============================================",
      "",
      `Verification ID: ${verificationId}`,
      `Generated: ${generatedAt.toISOString()}`,
      "",
      "Pro bono mentor / advisor logs:",
      ...MENTOR_LOGS.map(
        (l) =>
          `  - ${l.advisor} — ${l.focus} — ${formatHoursMinutes(l.minutes)}`,
      ),
      `  - Live workspace session — ${formatHoursMinutes(Math.round(sessionMinutes))}`,
      "",
      "Corporate CSR campaign attribution:",
      ...CSR_CAMPAIGNS.map((c) => {
        const pct = Math.min(100, (totalHours / c.targetHours) * 100);
        return `  - ${c.name}: ${totalHours.toFixed(2)}h of ${c.targetHours}h target (${pct.toFixed(0)}%)`;
      }),
      "",
      `Total verified impact hours: ${totalHours.toFixed(2)}h`,
      "",
      "This certificate is a data-verified record generated by the ProReady",
      "residency ledger for corporate HR documentation.",
      "",
    ];
    const blob = new Blob([lines.join("\n")], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = `csr-impact-certificate-${verificationId}.txt`;
    document.body.appendChild(anchor);
    anchor.click();
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);
  };

  return (
    <Card>
      <CardHeader>
        <div className="flex flex-wrap items-start justify-between gap-2">
          <div>
            <CardTitle className="flex items-center gap-2 text-base">
              <HeartHandshake className="size-4 text-primary" /> CSR Volunteer
              Hour Tracker
            </CardTitle>
            <CardDescription>
              Pro bono mentor advisor logs, accumulating live toward corporate
              CSR campaigns.
            </CardDescription>
          </div>
          <Badge variant="secondary">
            <Clock className="mr-1 size-3" />
            {formatHoursMinutes(Math.round(totalMinutes))} tracked
          </Badge>
        </div>
      </CardHeader>
      <CardContent className="space-y-5">
        <div>
          <div className="mb-2 flex items-center gap-2 text-sm font-semibold">
            <Award className="size-4 text-primary" /> Mentor advisor logs
          </div>
          <ul className="space-y-2">
            {MENTOR_LOGS.map((log) => (
              <li
                key={`${log.advisor}-${log.focus}`}
                className="flex items-center justify-between rounded-md border bg-card px-3 py-2 text-sm"
              >
                <span className="min-w-0">
                  <span className="block truncate font-medium">
                    {log.advisor}
                  </span>
                  <span className="block truncate text-xs text-muted-foreground">
                    {log.focus}
                  </span>
                </span>
                <span className="shrink-0 text-xs font-semibold tabular-nums text-muted-foreground">
                  {formatHoursMinutes(log.minutes)}
                </span>
              </li>
            ))}
            <li className="flex items-center justify-between rounded-md border border-dashed bg-primary/5 px-3 py-2 text-sm">
              <span className="min-w-0">
                <span className="block truncate font-medium">
                  Live workspace session
                </span>
                <span className="block truncate text-xs text-muted-foreground">
                  Auto-tracked since you opened this dashboard
                </span>
              </span>
              <span className="shrink-0 text-xs font-semibold tabular-nums text-primary">
                {formatHoursMinutes(Math.round(sessionMinutes))}
              </span>
            </li>
          </ul>
        </div>

        <div className="space-y-3">
          <div className="text-sm font-semibold">Campaign attribution</div>
          {CSR_CAMPAIGNS.map((campaign) => {
            const pct = Math.min(100, (totalHours / campaign.targetHours) * 100);
            return (
              <div key={campaign.id} className="space-y-1.5">
                <div className="flex items-baseline justify-between gap-2">
                  <span className="text-sm text-foreground">
                    {campaign.name}
                  </span>
                  <span className="shrink-0 text-xs tabular-nums text-muted-foreground">
                    {totalHours.toFixed(1)}h / {campaign.targetHours}h
                  </span>
                </div>
                <Progress value={pct} />
              </div>
            );
          })}
        </div>

        <Button className="w-full" onClick={handleExport}>
          <Download className="size-4" /> Export Verified CSR Impact Hour
          Certificate
        </Button>
      </CardContent>
    </Card>
  );
}
